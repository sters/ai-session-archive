import { Database } from "bun:sqlite";
import { mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { userText } from "./sync";

export function openDb(path: string): Database {
  if (path !== ":memory:") mkdirSync(dirname(path), { recursive: true });
  const db = new Database(path, { create: true, strict: true });
  db.run("PRAGMA journal_mode = WAL");
  db.run("PRAGMA busy_timeout = 10000");
  db.run(`CREATE TABLE IF NOT EXISTS sessions (
    rowid INTEGER PRIMARY KEY,
    id TEXT NOT NULL,
    parent_id TEXT,
    file_path TEXT NOT NULL UNIQUE,
    project_dir TEXT NOT NULL,
    cwd TEXT,
    git_branch TEXT,
    title TEXT,
    agent_type TEXT,
    description TEXT,
    first_ts TEXT,
    last_ts TEXT,
    imported_bytes INTEGER NOT NULL DEFAULT 0
  )`);
  // Sessions imported by an older build have a lower import_version and are imported again by `sync`
  // while their transcript still exists.
  const columns = db.query<{ name: string }, []>("SELECT name FROM pragma_table_info('sessions')").all();
  if (!columns.some((c) => c.name === "import_version")) {
    db.run("ALTER TABLE sessions ADD COLUMN import_version INTEGER NOT NULL DEFAULT 0");
  }
  db.run("CREATE INDEX IF NOT EXISTS sessions_id ON sessions(id)");
  db.run("CREATE INDEX IF NOT EXISTS sessions_parent ON sessions(parent_id)");
  db.run(`CREATE TABLE IF NOT EXISTS messages (
    id INTEGER PRIMARY KEY,
    session INTEGER NOT NULL REFERENCES sessions(rowid),
    ts TEXT,
    role TEXT NOT NULL,
    tool TEXT,
    text TEXT NOT NULL
  )`);
  db.run("CREATE INDEX IF NOT EXISTS messages_session ON messages(session, id)");
  // One row per transcript line that carries metadata, in file order: the line as JSON with its text,
  // tool input and tool output stripped (see `strip` in sync.ts). Token usage, cost-state and turn
  // durations are kept as Claude Code wrote them.
  db.run(`CREATE TABLE IF NOT EXISTS records (
    id INTEGER PRIMARY KEY,
    session INTEGER NOT NULL REFERENCES sessions(rowid),
    ts TEXT,
    data TEXT NOT NULL
  )`);
  db.run("CREATE INDEX IF NOT EXISTS records_session ON records(session, id)");
  // Generated by `summarize`. `start` is the local date the period begins on (a week begins on Monday,
  // a month on its 1st). `source` fingerprints the input the summary was written from; a summary whose
  // input has changed since is written again.
  db.run(`CREATE TABLE IF NOT EXISTS summaries (
    period TEXT NOT NULL CHECK (period IN ('day', 'week', 'month')),
    start TEXT NOT NULL,
    text TEXT NOT NULL,
    source TEXT NOT NULL,
    model TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (period, start)
  )`);
  // Calendar totals per period (see totals.ts), rewritten in full by every sync. Unlike summaries they cover the
  // current period too, and sessions started through the SDK.
  db.run(`CREATE TABLE IF NOT EXISTS period_stats (
    period TEXT NOT NULL CHECK (period IN ('day', 'week', 'month')),
    start TEXT NOT NULL,
    sessions INTEGER NOT NULL,
    prompts INTEGER NOT NULL,
    active_ms INTEGER NOT NULL,
    cost_usd REAL NOT NULL,
    lines_added INTEGER NOT NULL,
    lines_removed INTEGER NOT NULL,
    prs INTEGER NOT NULL,
    PRIMARY KEY (period, start)
  )`);
  // trigram so that Japanese, which has no word boundaries, matches by substring.
  db.run(`CREATE VIRTUAL TABLE IF NOT EXISTS messages_fts USING fts5(
    text, content='messages', content_rowid='id', tokenize='trigram'
  )`);
  db.run(`CREATE TRIGGER IF NOT EXISTS messages_ai AFTER INSERT ON messages BEGIN
    INSERT INTO messages_fts(rowid, text) VALUES (new.id, new.text);
  END`);
  db.run(`CREATE TRIGGER IF NOT EXISTS messages_ad AFTER DELETE ON messages BEGIN
    INSERT INTO messages_fts(messages_fts, rowid, text) VALUES ('delete', old.id, old.text);
  END`);
  // user_version 1: user messages hold only what the user typed (see `userText`), also in sessions whose
  // transcript is gone and that cannot be imported again.
  if (db.query<{ user_version: number }, []>("PRAGMA user_version").get()!.user_version < 1) {
    const rows = db
      .query<{ id: number; text: string }, []>("SELECT id, text FROM messages WHERE role = 'user' AND text LIKE '<%'")
      .all();
    const remove = db.query("DELETE FROM messages WHERE id = ?");
    const unindex = db.query("INSERT INTO messages_fts(messages_fts, rowid, text) VALUES ('delete', ?, ?)");
    const update = db.query("UPDATE messages SET text = ? WHERE id = ?");
    const index = db.query("INSERT INTO messages_fts(rowid, text) VALUES (?, ?)");
    db.transaction(() => {
      for (const r of rows) {
        const typed = userText(r.text);
        if (typed === r.text) continue;
        if (typed === null) {
          remove.run(r.id);
          continue;
        }
        unindex.run(r.id, r.text);
        update.run(typed, r.id);
        index.run(r.id, typed);
      }
      db.run("PRAGMA user_version = 1");
    })();
  }
  return db;
}
